def read_text(path):
    for img_file in os.listdir(path):
        if not img_file.endswith('.jpg'):
            continue
        if not img_file.startswith('YG-'):
            continue
        if "{}/{}".format(path, img_file) in lst:
            continue
        #print(img_file)
        call_google_cv("{}/{}".format(path, img_file))


def call_google_cv(img_file):
    print("calling -> " + img_file)
    with io.open(os.path.abspath(img_file), 'rb') as image_file:
        image_content = image_file.read()
        image = types.Image(content=image_content)
        response = client.document_text_detection(image=image)
        #print(len(response.full_text_annotation.pages))
        result = []
        for page in response.full_text_annotation.pages:
            for block in page.blocks:
                for paragraph in block.paragraphs:
                    for word in paragraph.words:
                        word_text = ''.join([
                            symbol.text for symbol in word.symbols
                        ])
                        result.append(word_text)
        # Save File
        file_name = Path(img_file).name
        with open("data/raw-text/2019/{}.txt".format("YG.txt"), "a", encoding="utf-8") as file:
            file.write(''.join(result) + "\n")
        if response.error.message:
            raise Exception('{}\nFor more info on error messages, check: '
                'https://cloud.google.com/apis/design/errors'.format(
                    response.error.message))


